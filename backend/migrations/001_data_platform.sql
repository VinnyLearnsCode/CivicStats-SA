CREATE TABLE data_sources (
  source_id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  source_url TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE source_datasets (
  dataset_id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL REFERENCES data_sources(source_id),
  title TEXT NOT NULL,
  source_url TEXT NOT NULL,
  api_url TEXT,
  geographic_level TEXT NOT NULL,
  unit TEXT NOT NULL,
  update_frequency TEXT NOT NULL,
  validation_status TEXT NOT NULL DEFAULT 'incomplete'
    CHECK (validation_status IN ('verified', 'awaiting_validation', 'partially_verified', 'outdated', 'incomplete', 'failed_import')),
  publication_status TEXT NOT NULL DEFAULT 'unpublished'
    CHECK (publication_status IN ('published', 'unpublished')),
  last_imported_at TIMESTAMPTZ,
  last_verified_at TIMESTAMPTZ
);

CREATE TABLE municipality_crosswalks (
  source_id TEXT NOT NULL REFERENCES data_sources(source_id),
  source_code TEXT NOT NULL,
  municipality_code TEXT NOT NULL,
  source_name TEXT NOT NULL,
  province_name TEXT NOT NULL,
  validation_status TEXT NOT NULL
    CHECK (validation_status IN ('verified', 'pending_validation')),
  validated_at TIMESTAMPTZ,
  PRIMARY KEY (source_id, source_code)
);

CREATE TABLE import_jobs (
  import_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id TEXT NOT NULL REFERENCES source_datasets(dataset_id),
  municipality_code TEXT NOT NULL,
  reporting_period TEXT NOT NULL,
  idempotency_key TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL
    CHECK (status IN ('running', 'awaiting_review', 'partial', 'failed', 'approved', 'rejected')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  records_retrieved INTEGER NOT NULL DEFAULT 0 CHECK (records_retrieved >= 0),
  records_accepted INTEGER NOT NULL DEFAULT 0 CHECK (records_accepted >= 0),
  records_rejected INTEGER NOT NULL DEFAULT 0 CHECK (records_rejected >= 0),
  error_message TEXT
);

CREATE INDEX import_jobs_started_at_idx ON import_jobs (started_at DESC);
CREATE INDEX import_jobs_geography_period_idx
  ON import_jobs (municipality_code, reporting_period, started_at DESC);

CREATE TABLE raw_data_records (
  raw_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_id BIGINT NOT NULL REFERENCES import_jobs(import_id),
  dataset_id TEXT NOT NULL REFERENCES source_datasets(dataset_id),
  municipality_code TEXT NOT NULL,
  source_code TEXT NOT NULL,
  reporting_period TEXT NOT NULL,
  record_key TEXT NOT NULL,
  content_hash TEXT NOT NULL,
  source_record JSONB NOT NULL,
  source_url TEXT NOT NULL,
  validation_status TEXT NOT NULL DEFAULT 'awaiting_validation'
    CHECK (validation_status IN ('awaiting_validation', 'verified', 'rejected')),
  publication_status TEXT NOT NULL DEFAULT 'unpublished'
    CHECK (publication_status IN ('published', 'unpublished')),
  imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (import_id, record_key, content_hash)
);

CREATE INDEX raw_data_records_review_idx
  ON raw_data_records (validation_status, publication_status, imported_at DESC);

CREATE TABLE data_quality_issues (
  issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_id BIGINT NOT NULL REFERENCES import_jobs(import_id),
  severity TEXT NOT NULL CHECK (severity IN ('warning', 'error')),
  issue_code TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE data_records (
  record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raw_record_id BIGINT NOT NULL UNIQUE REFERENCES raw_data_records(raw_record_id),
  dataset_id TEXT NOT NULL REFERENCES source_datasets(dataset_id),
  municipality_code TEXT NOT NULL,
  reporting_period TEXT NOT NULL,
  record_key TEXT NOT NULL,
  source_record JSONB NOT NULL,
  source_url TEXT NOT NULL,
  source_publication_date DATE,
  approved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (dataset_id, municipality_code, reporting_period, record_key)
);

CREATE INDEX data_records_municipality_period_idx
  ON data_records (dataset_id, municipality_code, reporting_period);
